// Human-readable instance labels are view data, never object names or IDs.
// Pass the full scene before filtering a dropdown so every view agrees.
const text=value=>String(value??'').trim();
const baseName=entity=>text(entity?.name)||text(entity?.spec?.name)||text(entity?.asset)||'Предмет';
const key=entity=>text(entity?.id??entity?.spec?.id??entity?.soft?.handle??entity?.body?.handle);
function hash(id){let h=2166136261;for(let i=0;i<id.length;i++){h^=id.charCodeAt(i);h=Math.imul(h,16777619);}return(h>>>0).toString(36).toUpperCase().padStart(7,'0');}
function suffix(id,generatorId=''){
 // The cell/source indices generated by the composer are already stable.
 // A generator is user-named; its ID need not start with "layout-".
 if(generatorId&&id.startsWith(generatorId+'-')){
  const instance=/^(\d+)-(\d+)$/.exec(id.slice(generatorId.length+1));
  if(instance){const cell=Number(instance[1])+1,source=Number(instance[2])+1;return source===1?String(cell):`${cell}.${source}`;}
 }
 const layout=/^layout-.+-(\d+)-(\d+)$/.exec(id);
 if(layout){const cell=Number(layout[1])+1,source=Number(layout[2])+1;return source===1?String(cell):`${cell}.${source}`;}
 const array=/^array-.+-(\d+)-(\d+)$/.exec(id);
 if(array)return`${Number(array[1])+1}.${Number(array[2])+1}`;
 const released=/^(?:added|emitter)-.+-(\d+)$/.exec(id);
 if(released)return String(Number(released[1])+1);
 const number=/(?:^|-)(\d{1,4})$/.exec(id);
 return number?String(Number(number[1])):hash(id).slice(-4);
}
const ordered=(a,b)=>a.localeCompare(b,'en',{numeric:true,sensitivity:'variant'});

/** Returns Map<stable entity id, displayed label>; works for rigid and soft bodies. */
export function objectLabelMap(entities=[]){
 const entries=new Map();
 for(const entity of Array.isArray(entities)?entities:[]){const id=key(entity);if(entity&&id&&!entries.has(id))entries.set(id,{id,name:baseName(entity),generatorId:text(entity.generatorId)||text(entity.spec?.generatorId)});}
 const groups=new Map();for(const entry of entries.values()){if(!groups.has(entry.name))groups.set(entry.name,[]);groups.get(entry.name).push(entry);}
 const result=new Map(),reserved=new Set();
 for(const[name,group]of groups)if(group.length===1){result.set(group[0].id,name);reserved.add(name);}
 for(const[name,group]of [...groups].sort(([a],[b])=>ordered(a,b))){
  if(group.length===1)continue;
  const candidates=new Map();for(const entry of group){entry.suffix=suffix(entry.id,entry.generatorId);if(!candidates.has(entry.suffix))candidates.set(entry.suffix,[]);candidates.get(entry.suffix).push(entry);}
  for(const entry of group.slice().sort((a,b)=>ordered(a.id,b.id))){
   const conflicts=candidates.get(entry.suffix);let label=`${name} · ${entry.suffix}`;
   if(conflicts.length>1||reserved.has(label)){
    const code=hash(entry.id);let size=3;
    while(size<code.length&&conflicts.some(other=>other.id!==entry.id&&hash(other.id).slice(-size)===code.slice(-size)))size++;
    label=`${name} · ${entry.suffix}-${code.slice(-size)}`;
    // A deliberately renamed object can equal a generated label. Keep the
    // user's unique name and extend this display-only suffix deterministically.
    if(reserved.has(label))label=`${name} · ${entry.suffix}-${code}`;
    if(reserved.has(label)){const rank=group.map(e=>e.id).sort(ordered).indexOf(entry.id)+1;label+=`-${rank}`;}
   }
   result.set(entry.id,label);reserved.add(label);
  }
 }
 return result;
}

/** Convenience lookup using a precomputed map or the full scene entity list. */
export function objectLabel(entity,mapOrEntities=[]){
 const labels=mapOrEntities instanceof Map?mapOrEntities:objectLabelMap(mapOrEntities);
 return labels.get(key(entity))||baseName(entity);
}
